// Turns the Expo web export (apps/mobile/dist) into function/web-assets.ts so it ships inside the function bundle.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(process.argv[2] ?? '../mobile/dist');
const out = path.resolve(process.argv[3] ?? 'function/web-assets.ts');
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'application/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.json': 'application/json', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.ico': 'image/x-icon',
  '.ttf': 'font/ttf', '.woff': 'font/woff', '.woff2': 'font/woff2', '.map': 'application/json',
};
const files = {};
let bytes = 0;
const walk = (dir) => {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full);
    else {
      const data = fs.readFileSync(full);
      bytes += data.length;
      files['/' + path.relative(root, full).split(path.sep).join('/')] = {
        type: TYPES[path.extname(name)] ?? 'application/octet-stream', base64: data.toString('base64'),
      };
    }
  }
};
if (!fs.existsSync(path.join(root, 'index.html'))) throw new Error(`No web export at ${root}. Run the mobile web export first.`);
walk(root);
fs.writeFileSync(out, `// Generated by function/embed-web.mjs. Do not edit or commit.\nexport const WEB_FILES: Record<string, { type: string; base64: string }> = ${JSON.stringify(files)};\n`);
console.log(`Embedded ${Object.keys(files).length} files (${(bytes / 1024 / 1024).toFixed(1)} MiB) into ${path.relative(process.cwd(), out)}`);
